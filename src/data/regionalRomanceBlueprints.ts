/**
 * Generates clean, valid map locations for ALL 39 regional romance chapters
 * covering every World Bloc (including previously empty Veridia, Teselia, Shentai, Kovaria, Borelia & Kora!).
 */
export function buildRomanceMapLocations(): Record<string, ChapterMapLocation> {
  const map: Record<string, ChapterMapLocation> = {};
  for (const bp of Object.values(REGIONAL_ROMANCE_BLUEPRINTS)) {
    map[`romance-${bp.npcId}-r1`] = {
      chapterId: `romance-${bp.npcId}-r1`,
      blocId: bp.r1.blocId,
      locationName: bp.r1.locationName,
      regionLabel: `${bp.regionShort} · Vínculo I (Duelo)`,
      theaterNote: bp.r1.theaterNote,
      coords: bp.r1.coords,
      zoom: bp.r1.zoom,
    };
    map[`romance-${bp.npcId}-r2`] = {
      chapterId: `romance-${bp.npcId}-r2`,
      blocId: bp.r2.blocId,
      locationName: bp.r2.locationName,
      regionLabel: `${bp.regionShort} · Vínculo II (Amigos 2v2)`,
      theaterNote: bp.r2.theaterNote,
      coords: bp.r2.coords,
      zoom: bp.r2.zoom,
    };
    map[`romance-${bp.npcId}-r3`] = {
      chapterId: `romance-${bp.npcId}-r3`,
      blocId: bp.r3.blocId,
      locationName: bp.r3.locationName,
      regionLabel: `${bp.regionShort} · Vínculo III (Revancha Nv.${bp.r3.levelCap}+)`,
      theaterNote: bp.r3.theaterNote,
      coords: bp.r3.coords,
      zoom: bp.r3.zoom,
    };
  }
  return map;
}
